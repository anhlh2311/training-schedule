/**
 * Generates public/firebase-messaging-sw.js with Firebase config from env.
 * Run before build: node scripts/generate-firebase-sw.cjs
 * Loads .env from project root if present.
 */
const fs = require("fs");
const path = require("path");

const envPath = path.join(__dirname, "..", ".env");
if (fs.existsSync(envPath)) {
  const content = fs.readFileSync(envPath, "utf8");
  for (const line of content.split("\n")) {
    const m = line.match(/^([A-Za-z_][A-Za-z0-9_]*)=(.*)$/);
    if (m) process.env[m[1].trim()] = m[2].trim().replace(/^["']|["']$/g, "");
  }
}

const config = {
  apiKey: process.env.VITE_FIREBASE_API_KEY || "",
  authDomain: process.env.VITE_FIREBASE_AUTH_DOMAIN || "",
  projectId: process.env.VITE_FIREBASE_PROJECT_ID || "",
  storageBucket: process.env.VITE_FIREBASE_STORAGE_BUCKET || "",
  messagingSenderId: process.env.VITE_FIREBASE_MESSAGING_SENDER_ID || "",
  appId: process.env.VITE_FIREBASE_APP_ID || "",
};

const swContent = `// Generated by scripts/generate-firebase-sw.cjs - do not edit manually
importScripts("https://www.gstatic.com/firebasejs/12.10.0/firebase-app-compat.js");
importScripts("https://www.gstatic.com/firebasejs/12.10.0/firebase-messaging-compat.js");

firebase.initializeApp(${JSON.stringify(config)});
const messaging = firebase.messaging();

messaging.onBackgroundMessage(function (payload) {
  // Server sends data-only messages (title/body in data) so this is the single
  // display path on web — FCM does not reliably auto-show \`notification\` on
  // Chrome/Safari. Fallback to \`notification\` for older cached payloads.
  const data = payload.data || {};
  const title =
    data.title || payload.notification?.title || "Training Schedule";
  const body = data.body || payload.notification?.body || "";
  const options = {
    body,
    icon:
      payload.notification?.icon ||
      data.icon ||
      "/IHN-Logo-1000x1000.png",
    tag: data.tag || "training-schedule",
    data: Object.keys(data).length ? data : { url: "/" },
  };
  return self.registration.showNotification(title, options);
});

self.addEventListener("notificationclick", function (event) {
  event.notification.close();
  const url = event.notification.data?.url || "/";
  event.waitUntil(
    clients.matchAll({ type: "window", includeUncontrolled: true }).then(function (clientList) {
      for (const client of clientList) {
        if (client.url.includes(self.location.origin) && "focus" in client) {
          client.navigate(url);
          return client.focus();
        }
      }
      if (clients.openWindow) return clients.openWindow(url);
    })
  );
});
`;

const outDir = path.join(__dirname, "..", "public");
const outPath = path.join(outDir, "firebase-messaging-sw.js");
if (!fs.existsSync(outDir)) fs.mkdirSync(outDir, { recursive: true });
fs.writeFileSync(outPath, swContent, "utf8");
console.log("Wrote", outPath);
